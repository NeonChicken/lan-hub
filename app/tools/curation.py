def _merge():
    """Public catalog + your curation_local.py (your entries win when the id matches)."""
    try:
        import curation_local as mine
    except ImportError:
        mine = None
    local = list(getattr(mine, "LOCAL", []) or [])
    ids = {e.get("id") for e in local}
    base = lambda p: re.split(r"[\\/]", p)[-1].lower() if isinstance(p, str) and p else None
    files = {base(e.get(k)) for e in local for k in ("launch", "install")} - {None}
    STEAM.update(getattr(mine, "STEAM", {}) or {})
    public = [e for e in CLASSICS if e["id"] not in ids and not ({base(e.get("launch")), base(e.get("install"))} & files)]
    return public + local, list(getattr(mine, "CURATOR_ROOTS", []) or []), mine is not None


